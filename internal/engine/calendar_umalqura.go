// The Umm al-Qura calendar, as a table.
//
// This calendar is not a rule. Saudi Arabia publishes it year by year from the
// sighting of the moon in Mecca, so the only honest implementation is the
// published table: twelve bits per year from 1300 AH, one per month, set where
// the month has thirty days. Outside the tabulated range the civil arithmetic
// stands in, which is what ICU does and what a date that far out deserves.
//
// The table is ICU's UMALQURA_MONTHLENGTH, read the same way: the high bit of
// the twelve is the first month. The last four years are ICU's too, taken from
// the binary spellings in its comments -- its array stops at 1596 while its own
// range check says 1600, so the four are written out here rather than read off
// the end of it.

// umalquraFirstYear is the first Hijri year the table covers.
